/**
 * Get a random hero image
 */
export const getRandomHeroImage = (): string => {
  const index = Math.floor(Math.random() * heroImages.length);
  return heroImages[index];
};

/**
 * Get hero image by index (with wraparound)
 */
export const getHeroImageByIndex = (index: number): string => {
  return heroImages[index % heroImages.length];
};

/**
 * Get random camp image
 */
export const getRandomCampImage = (): string => {
  const campImages = cardBackgrounds.summerCamps;
  return campImages[Math.floor(Math.random() * campImages.length)];
};

/**
 * Get random clinic image
 */
export const getRandomClinicImage = (): string => {
  const clinicImages = cardBackgrounds.winterClinics;
  return clinicImages[Math.floor(Math.random() * clinicImages.length)];
};

